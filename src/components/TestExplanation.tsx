import type { TestDescription } from '../lib/public-types';

export default function TestExplanation({ explanation, category = false, heading }: { explanation?: TestDescription; category?: boolean; heading?: string }) {
  if (!explanation) return null;
  return <section className="test-explanation" aria-label={category ? 'About this category' : 'What this task tests'}>
    <h2>{heading ?? (category ? 'What these tests cover' : explanation.title ?? 'What this task tests')}</h2>
    <p>{explanation.description}</p>
    <details><summary>About this explanation</summary><small>Generated by {explanation.generator.display_name_at_generation} ({explanation.generator.model_id_requested}) · {explanation.generated_at.slice(0,10)}. Shared across models for this version of the test. The original question and checks remain the source of truth.</small></details>
  </section>;
}
