import { expect, test } from '@playwright/test';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { gunzipSync } from 'node:zlib';
import { importRelease } from '../../scripts/import-data.mjs';
import { verifyRelease } from '../../scripts/public-data.mjs';
import { archiveUrl } from '../../src/lib/edition-client';
import { comparisonUrl } from '../../src/lib/comparison';
import type { PublicResultsReleaseV1 } from '../../src/lib/public-release';

test('regrade promotion and rollback preserve historical grade, evidence and analyst identity', async ({ page }) => {
  const root = await mkdtemp(join(tmpdir(), 'edition-browser-'));
  const source = resolve('tests/fixtures/edition-history-v1');
  try {
    const oldId = await importRelease(join(source, 'release'), root, { progress: false });
    const original = await readFile(join(root, 'releases', oldId, 'release.json'));
    const newId = await importRelease(join(source, 'regraded'), root, { progress: false });
    expect(JSON.parse(await readFile(join(root, 'latest.json'), 'utf8')).release_id).toBe(newId);
    expect(await readFile(join(root, 'releases', oldId, 'release.json'))).toEqual(original);
    const old = (await verifyRelease(root, { releasePath: `releases/${oldId}/release.json` })).release as PublicResultsReleaseV1;
    const object = old.objects.find((o: {id: string}) => o.id === old.index_object_id)!;
    const bytes = await readFile(join(root, object.path));
    const index = JSON.parse((object.encoding === 'gzip' ? gunzipSync(bytes) : bytes).toString());
    const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
    await page.route('**/data/**', async route => {
      const path = new URL(route.request().url()).pathname.slice('/data/'.length);
      if (!/^(releases\/release-[a-f0-9]{64}\/release\.json|objects\/sha256\/[a-f0-9]{64}\.(json|txt)(\.gz)?|latest\.json)$/.test(path)) return route.fulfill({ status: 404 });
      try { await route.fulfill({ body: await readFile(join(root, path)), contentType: path.endsWith('.gz') ? 'application/octet-stream' : 'application/json' }); }
      catch { await route.fulfill({ status: 404 }); }
    });
    const selections = index.configurations.map((config: {id: string}) => ({ configurationId: config.id,
      conditionId: index.conditions.find((condition: {configuration_id: string}) => condition.configuration_id === config.id).id }));
    const comparison = { releaseId: oldId, suiteId: index.suites[0].id, selections };
    await page.goto(comparisonUrl(comparison));
    await expect(page.locator('.score').first()).toHaveText('1/1 full credit');
    await expect(page.locator('.score').nth(1)).toHaveText('Not scored');
    await page.getByRole('button', { name: 'Open recorded answers' }).click();
    await expect(page.getByText(/100\.0% credit/)).toBeVisible();
    await expect(page.getByText('No canonical result for this exact trial.')).toBeVisible();
    await page.reload();
    await expect(page.getByText(/100\.0% credit/)).toBeVisible();
    await page.goto(comparisonUrl({ ...comparison, releaseId: newId }));
    await expect(page.locator('.score').first()).toHaveText('0/1 full credit');
    await page.goBack(); await expect(page.locator('.score').first()).toHaveText('1/1 full credit');
    const model = { checkpoint: index.checkpoints[0].id };
    await page.goto(archiveUrl(oldId, model));
    await expect(page.getByRole('heading', { name: 'Model analysis', exact: true })).toBeVisible();
    await expect(page.getByText('Summary generated by GPT Astra', { exact: true })).toBeVisible();
    await page.getByText('About this summary', { exact: true }).click();
    await expect(page.getByText('Exact provider snapshot not supplied.', { exact: true }).first()).toBeVisible();
    await page.goto(archiveUrl(newId, model));
    await expect(page.getByRole('heading', { name: 'Factual assessment', exact: true })).toBeVisible();
    await expect(page.getByRole('heading', { name: 'Model analysis', exact: true })).toHaveCount(0);
    const question = { question: index.questions[0].id };
    await page.goto(archiveUrl(oldId, question));
    await expect(page.getByText(/100\.0% credit/)).toBeVisible();
    const answer = page.locator('.evidence pre').last(); await expect(answer).toBeVisible();
    const exactAnswer = await answer.textContent();
    await page.goto(archiveUrl(newId, question));
    await expect(page.getByText(/0\.0% credit/)).toBeVisible();
    await expect(page.locator('.evidence pre').last()).toHaveText(exactAnswer!);
    await page.goBack(); await expect(page.getByText(/100\.0% credit/)).toBeVisible();
    await importRelease(join(source, 'release'), root, { progress: false });
    expect(JSON.parse(await readFile(join(root, 'latest.json'), 'utf8')).release_id).toBe(oldId);
    await verifyRelease(root, { releasePath: `releases/${newId}/release.json` });
    await page.goto(archiveUrl(newId, question));
    await expect(page.getByText(/0\.0% credit/)).toBeVisible();
    expect(errors).toEqual([]);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  } finally { await rm(root, { recursive: true, force: true }); }
});
