import {expect,test} from '@playwright/test';
import {mkdtemp,readFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {importRelease} from '../../scripts/import-data.mjs';
import {readObject,verifyRelease} from '../../scripts/public-data.mjs';
import {archiveUrl} from '../../src/lib/edition-client';
import type {PublicResultsReleaseV1} from '../../src/lib/public-release';

test('one shared quant assessment follows variant selection and exact archived answer links',async({page})=>{
  const root=await mkdtemp(join(tmpdir(),'quant-browser-'));
  try {
    const id=await importRelease(resolve('tests/fixtures/quant-release-v1'),root,{progress:false});
    const verified=await verifyRelease(root,{releasePath:`releases/${id}/release.json`});
    const release=verified.release as PublicResultsReleaseV1;
    const ref=release.quant_summary_objects![0];
    const packet=JSON.parse((await readObject(root,release.objects.find(o=>o.id===ref.facts_object_id)!)).toString());
    const group=packet.inputs.groups[0];const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
    await page.route('**/data/**',async route=>{
      const path=new URL(route.request().url()).pathname.slice('/data/'.length);
      if(!/^(releases\/release-[a-f0-9]{64}\/release\.json|objects\/sha256\/[a-f0-9]{64}\.(json|txt)(\.gz)?|latest\.json)$/.test(path))return route.fulfill({status:404});
      try{await route.fulfill({body:await readFile(join(root,path)),contentType:path.endsWith('.gz')?'application/octet-stream':'application/json'});}catch{await route.fulfill({status:404});}
    });
    await page.goto(archiveUrl(id,{checkpoint:ref.checkpoint_id,configuration:group.rows[0].configuration_id,condition:group.rows[0].condition_id,suite:group.suite_id}));
    const section=page.locator('#choosing-a-quant');await expect(section.getByRole('heading',{name:'Choosing a quant'})).toBeVisible();
    await expect(section.getByText(/Quant comparison generated by GPT Astra/)).toBeVisible();
    await section.getByText('Evidence for this judgment',{exact:true}).click();
    await section.getByText('About this quant assessment',{exact:true}).click();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth)).toBe(true);
    expect(await section.locator('tbody tr').first().evaluate(row=>row.getBoundingClientRect().height)).toBeLessThan(180);
    await section.screenshot({path:`test-results/quant-section-${test.info().project.name}.png`});
    await expect(section.getByText('Selected format',{exact:true})).toHaveCount(1);
    await page.locator('#model-configuration').selectOption(group.rows[1].configuration_id);
    await expect(section.getByText('Selected format',{exact:true})).toHaveCount(1);
    const answer=section.getByRole('link',{name:'Answers and code'}).nth(1);await answer.click();
    await expect(page).toHaveURL(new RegExp('configuration='+group.rows[1].configuration_id));
    await expect(page).toHaveURL(new RegExp('release='+id));
    await expect(page.locator('#recorded-answers')).toBeVisible();
    expect(errors).toEqual([]);expect(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth)).toBe(true);
  } finally {await rm(root,{recursive:true,force:true});}
});
