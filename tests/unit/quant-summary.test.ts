import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { expect,it } from 'vitest';
import { readObject,verifyRelease } from '../../scripts/public-data.mjs';
import { verifyQuantSummary } from '../../scripts/quant-data.mjs';
import { canonical } from '../../src/lib/canonical.mjs';
import { createHash } from 'node:crypto';
import QuantSummary from '../../src/components/QuantSummary';
import type { QuantView } from '../../src/lib/quant-view';
const root=fileURLToPath(new URL('../fixtures/quant-release-v1/',import.meta.url));
async function fixture(){const manifest=JSON.parse(await readFile(root+'release.json','utf8'));const get=async(id:string)=>JSON.parse((await readObject(root,manifest.objects.find((o:{id:string})=>o.id===id))).toString());const ref=manifest.quant_summary_objects[0];return {manifest,data:await get(manifest.dataset_object_id),analysis:{summary:await get(ref.object_id),packet:await get(ref.facts_object_id)} as QuantView};}
it('independently verifies the synthetic shared comparison release',async()=>{
  await expect(verifyRelease(root)).resolves.toHaveProperty('release.quant_summary_objects');
  const {analysis,data}=await fixture();analysis.summary.content.synopsis.artifact_ids.push('outside');
  analysis.summary.summary_id='quant-summary-'+createHash('sha256').update(canonical(Object.fromEntries(Object.entries(analysis.summary).filter(([k])=>k!=='summary_id')))).digest('hex');
  expect(()=>verifyQuantSummary(analysis.summary,analysis.packet,data)).toThrow('outside');
});
it('renders shared attribution, selected quant, and exact edition-preserving answers',async()=>{
  const {manifest,analysis}=await fixture();const artifactId=analysis.packet.inputs.artifacts[0]!.id;
  const html=renderToStaticMarkup(createElement(QuantSummary,{analysis,artifactId,releaseId:manifest.release_id,archived:true}));
  expect(html).toContain('Choosing a quant');expect(html).toContain('Quant comparison generated by GPT Astra');
  expect(html).toContain('Selected format');expect(html).toContain('Q4_K_M');expect(html).toContain('Q8_0');
  expect(html).toContain('/archive/?');expect(html).toContain('release='+manifest.release_id);expect(html).toContain('#recorded-answers');
  expect(html).toContain('Weights, not required RAM');
});
it('does not apply the old comparison to a new quant or display an unapproved draft',async()=>{
  const {manifest,analysis}=await fixture();const props={analysis,artifactId:'not-in-this-assessment',releaseId:manifest.release_id};
  expect(renderToStaticMarkup(createElement(QuantSummary,props))).toContain('not included in this written comparison');
  analysis.summary.editorial={state:'draft',reviewed_at:null,edited:false,supersedes_summary_id:null};
  expect(renderToStaticMarkup(createElement(QuantSummary,props))).toBe('');
});
