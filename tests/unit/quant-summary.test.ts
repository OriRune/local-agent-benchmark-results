const root=fileURLToPath(new URL('../fixtures/quant-release-v1/',import.meta.url));
async function fixture(){const manifest=JSON.parse(await readFile(root+'release.json','utf8'));const get=async(id:string)=>JSON.parse((await readObject(root,manifest.objects.find((o:{id:string})=>o.id===id))).toString());const ref=manifest.quant_summary_objects[0];return {manifest,data:await get(manifest.dataset_object_id),analysis:{summary:await get(ref.object_id),packet:await get(ref.facts_object_id)} as QuantView};}
it('independently verifies the synthetic shared comparison release',async()=>{
  await expect(verifyRelease(root)).resolves.toHaveProperty('release.quant_summary_objects');
  const {analysis,data}=await fixture();analysis.summary.content.synopsis.artifact_ids.push('outside');
  analysis.summary.summary_id='quant-summary-'+createHash('sha256').update(canonical(Object.fromEntries(Object.entries(analysis.summary).filter(([k])=>k!=='summary_id')))).digest('hex');
  expect(()=>verifyQuantSummary(analysis.summary,analysis.packet,data)).toThrow('outside');
});
it('renders shared attribution, selected quant, and exact edition-preserving answers',async()=>{
  const {manifest,analysis}=await fixture();const artifactId=analysis.packet.inputs.artifacts[0]!.id;
  const html=renderToStaticMarkup(createElement(QuantSummary,{analysis,artifactId,releaseId:manifest.release_id,archived:true}));
  expect(html).toContain('Choosing a quant');expect(html).toContain('Quant comparison generated by GPT Astra');
  expect(html).toContain('Selected format');expect(html).toContain('Q4_K_M');expect(html).toContain('Q8_0');
  expect(html).toContain('/archive/?');expect(html).toContain('release='+manifest.release_id);expect(html).toContain('#recorded-answers');
  expect(html).toContain('Weights, not required RAM');
});
it('does not apply the old comparison to a new quant or display an unapproved draft',async()=>{
  const {manifest,analysis}=await fixture();const props={analysis,artifactId:'not-in-this-assessment',releaseId:manifest.release_id};
  expect(renderToStaticMarkup(createElement(QuantSummary,props))).toContain('not included in this written comparison');
  analysis.summary.editorial={state:'draft',reviewed_at:null,edited:false,supersedes_summary_id:null};
  expect(renderToStaticMarkup(createElement(QuantSummary,props))).toBe('');
});
it('labels agent quant review separately from user publication authorization',async()=>{
  const {manifest,analysis,data}=await fixture();
  if(analysis.summary.editorial.state!=='approved')throw new Error('Expected synthetic approved fixture');
  analysis.summary.editorial={...analysis.summary.editorial,reviewer_kind:'agent',reviewer_name:'Codex',publication_authorization:{
    authorized_by:'user',authorized_at:'2026-10-21T23:00:00Z',instruction:'Synthetic authorization to publish.'}};
  analysis.summary.summary_id='quant-summary-'+createHash('sha256').update(canonical(Object.fromEntries(Object.entries(analysis.summary).filter(([k])=>k!=='summary_id')))).digest('hex');
  expect(()=>verifyQuantSummary(analysis.summary,analysis.packet,data)).not.toThrow();
  const html=renderToStaticMarkup(createElement(QuantSummary,{analysis,artifactId:analysis.packet.inputs.artifacts[0]!.id,releaseId:manifest.release_id}));
  expect(html).toContain('Quant comparison generated by GPT Astra');
  expect(html).toContain('Agent reviewed by Codex');expect(html).toContain('publication authorized by user');
  expect(html).toContain('Synthetic authorization to publish.');expect(html.toLowerCase()).not.toContain('human reviewed');
  analysis.summary.editorial.publication_authorization.instruction='';
  analysis.summary.summary_id='quant-summary-'+createHash('sha256').update(canonical(Object.fromEntries(Object.entries(analysis.summary).filter(([k])=>k!=='summary_id')))).digest('hex');
  expect(()=>verifyQuantSummary(analysis.summary,analysis.packet,data)).toThrow('publication authorization');
});

async function v2Fixture(){
  const value=await fixture(),{analysis,data}=value;
  data.configurations.forEach((c:{observed:{cpu_moe_layers:number|null}},i:number)=>{c.observed.cpu_moe_layers=i?11:1;});
  const packet=quantPacket(data,analysis.summary.checkpoint_id,{policy:'checkpoint-quant-facts-v2',configurationIds:data.configurations.map((c:{id:string})=>c.id),inclusionEvidenceSha256:'a'.repeat(64)}) as QuantView['packet'];
  analysis.packet=packet;analysis.summary.evidence.analysis_input_hash=packet.analysis_input_hash;
  for(const claim of [analysis.summary.content.synopsis,...analysis.summary.content.observations])claim.group_ids=[packet.inputs.groups[0]!.id];
  analysis.summary.summary_id='quant-summary-'+createHash('sha256').update(canonical(Object.fromEntries(Object.entries(analysis.summary).filter(([k])=>k!=='summary_id')))).digest('hex');
  return value;
}
it('v2 independently rebuilds offload-qualified quality and freezes explicit completed membership',async()=>{
  const {analysis,data}=await v2Fixture();
  expect(analysis.packet.quant_facts_version).toBe(2);
  expect(analysis.packet.inputs.groups[0]!.timing_comparable).toBe(false);
  expect(analysis.packet.inputs.groups[0]!.rows.map(r=>r.execution_profile!.observed.cpu_moe_layers).sort((a,b)=>a!-b!)).toEqual([1,11]);
  expect(()=>verifyQuantSummary(analysis.summary,analysis.packet,data)).not.toThrow();
  const changed=structuredClone(data);changed.configurations[0].observed.cpu_moe_layers=7;
  expect(()=>verifyQuantSummary(analysis.summary,analysis.packet,changed)).toThrow('stale');
  analysis.packet.inputs.inclusion!.evidence_sha256='b'.repeat(64);
  expect(()=>verifyQuantSummary(analysis.summary,analysis.packet,data)).toThrow('stale');
});
it('v2 shows each recorded setup and suppresses task time when execution profiles differ',async()=>{
  const {analysis,manifest}=await v2Fixture();
  const html=renderToStaticMarkup(createElement(QuantSummary,{analysis,artifactId:analysis.packet.inputs.artifacts[0]!.id,releaseId:manifest.release_id}));
  expect(html).toContain('Matching task controls');expect(html).toContain('Task times are not comparable for this group.');
  expect(html).toContain('CPU MoE layers: 1');expect(html).toContain('CPU MoE layers: 11');
  expect(html).toContain('Recorded execution settings');expect(html).toContain('Not compared');
  expect(html).toContain('do not isolate the effect of bit depth');
});
