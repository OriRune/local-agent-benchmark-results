import { expect, it } from 'vitest';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import ModelSummary from '../../src/components/ModelSummary';
import { summaryView, summaryClaimText, factText } from '../../src/lib/summary-view';
import { readObject } from '../../scripts/public-data.mjs';
import type { PublicBenchmarkSummaryV1 } from '../../src/lib/public-summary';
import type { PublicResultsReleaseV1 } from '../../src/lib/public-release';

const root = fileURLToPath(new URL('../fixtures/summary-release-v1/', import.meta.url));
const release: PublicResultsReleaseV1 = JSON.parse(await readFile(`${root}/release.json`, 'utf8'));
const ref = release.summary_objects[0]!;
const summary: PublicBenchmarkSummaryV1 = JSON.parse((await readObject(root, release.objects.find(o => o.id === ref.object_id)!)).toString('utf8'));
const packet = JSON.parse((await readObject(root, release.objects.find(o => o.id === ref.facts_object_id)!)).toString('utf8'));
const analysis = summaryView(summary, packet);

it('renders approved configuration-scoped analysis with attribution and navigable fact evidence', () => {
  const html = renderToStaticMarkup(createElement(ModelSummary, { analysis, configurationId: ref.configuration_id }));
  expect(html).toContain('Summary generated by GPT Astra');
  expect(html).toContain('across its recorded thinking conditions');
  expect(html).toContain('Evidence for this judgment');
  expect(html).toContain('#recorded-results');
  expect(html).not.toContain('{{fact-');
});
it('does not apply analysis to another configuration or show an unapproved draft', () => {
  expect(renderToStaticMarkup(createElement(ModelSummary, { analysis, configurationId: 'other-config' }))).not.toContain('Summary generated by');
  const draft = structuredClone(analysis); draft.summary.editorial = { state: 'draft', reviewed_at: null, edited: false, supersedes_summary_id: null };
  expect(renderToStaticMarkup(createElement(ModelSummary, { analysis: draft, configurationId: ref.configuration_id }))).not.toContain('Summary generated by');
});
it('keeps model-authored markup inert and uses recorded numeric values', () => {
  const changed = structuredClone(analysis); changed.summary.content.verdict.text += '<script>alert("fixture")</script>';
  const html = renderToStaticMarkup(createElement(ModelSummary, { analysis: changed, configurationId: ref.configuration_id }));
  expect(html).toContain('&lt;script&gt;'); expect(html).not.toContain('<script>');
  expect(summaryClaimText(summary.content.verdict)).toContain('1 trial');
  expect(factText(1, 'questions')).toBe('1 question');
  expect(factText(2, 'questions')).toBe('2 questions');
  expect(factText(null, 'seconds')).toBe('not measured');
  expect(factText(0, 'normalized_credit')).toBe('0.0% average credit');
  expect(factText(-2, 'percentage_points')).toBe('-2.0 percentage points');
});

