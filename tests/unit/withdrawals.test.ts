import { afterEach, expect, it, vi } from 'vitest';
import { mkdtemp, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { importRelease } from '../../scripts/import-data.mjs';
import { readObject } from '../../scripts/public-data.mjs';
import { verifyRetained } from '../../scripts/retained-data.mjs';
import { withdrawEvidence } from '../../scripts/withdraw-evidence.mjs';
import { validateWithdrawals } from '../../src/lib/withdrawals.mjs';
import { assertObjectAvailable, assertEditionAvailable } from '../../src/lib/withdrawal-client';
const fixture = resolve('tests/fixtures/withdrawal-v2');
const roots: string[] = [];
afterEach(async () => { vi.unstubAllGlobals(); for (const root of roots.splice(0)) await rm(root, { recursive: true, force: true }); });

it('retires affected editions in a new tree, preserves the replacement, and prevents resurrection', async () => {
  const root = await mkdtemp(join(tmpdir(), 'withdrawal-test-')); roots.push(root);
  const source = join(root, 'source'), out = join(root, 'withdrawn');
  const old = await importRelease(join(fixture, 'original'), source, { progress: false });
  const manifest = JSON.parse(await readFile(join(fixture, 'original/release.json'), 'utf8'));
  const dataset = JSON.parse((await readObject(join(fixture, 'original'), manifest.objects.find((o: { id: string }) => o.id === manifest.dataset_object_id))).toString());
  const id = dataset.attempts[0].components.answer.object_ids[0];
  const options = { objectIds: [id], reason: 'Synthetic answer removal.', withdrawnAt: '2026-10-09T00:00:00.000Z' };
  await expect(withdrawEvidence(source, options)).rejects.toThrow('replacement');
  const current = await importRelease(join(fixture, 'replacement'), source, { progress: false });
  const preview = await withdrawEvidence(source, options);
  expect(preview).toMatchObject({ preview: true, selected: current, retired_editions: [old] });
  const result = await withdrawEvidence(source, { ...options, out });
  expect(result.preview).toBe(false);
  expect((await verifyRetained(out)).editions).toEqual([current]);
  expect((await verifyRetained(source)).editions).toEqual([old, current]);
  const record = manifest.objects.find((o: { id: string }) => o.id === id);
  await expect(stat(join(out, record.path))).rejects.toMatchObject({ code: 'ENOENT' });
  await expect(stat(join(out, 'releases', old))).rejects.toMatchObject({ code: 'ENOENT' });
  const registry = validateWithdrawals(JSON.parse(await readFile(join(out, 'withdrawals.json'), 'utf8')));
  expect(registry.objects[id].release_ids).toEqual([old]);
  expect(registry.editions[old].reason).toBe(options.reason);
  const registryBytes = await readFile(join(out, 'withdrawals.json'));
  await rm(join(out, 'withdrawals.json'));
  await expect(verifyRetained(out)).rejects.toThrow('registry');
  await writeFile(join(out, 'withdrawals.json'), registryBytes);
  await expect(importRelease(join(fixture, 'original'), out, { progress: false })).rejects.toThrow('withdrawn');
  const currentManifest = JSON.parse(await readFile(join(out, 'releases', current, 'release.json'), 'utf8'));
  const path = currentManifest.objects[0].path;
  await rm(join(out, path));
  await expect(verifyRetained(out)).rejects.toThrow();
});
it('checks withdrawal notices before cached content and rejects malformed or unavailable registries', async () => {
  const id = 'a'.repeat(64), release = 'release-' + 'b'.repeat(64);
  const registry = { version: 1, objects: { [id]: { reason: 'Removed by owner.', withdrawn_at: '2026-10-09T00:00:00.000Z', release_ids: [release] } }, editions: { [release]: { reason: 'Removed by owner.', withdrawn_at: '2026-10-09T00:00:00.000Z', object_ids: [id] } } };
  const fetch = vi.fn(async () => new Response(JSON.stringify(registry))); vi.stubGlobal('fetch', fetch);
  await expect(assertObjectAvailable(id)).rejects.toThrow('intentionally withdrawn');
  await expect(assertEditionAvailable(release)).rejects.toThrow('Removed by owner.');
  expect(fetch).toHaveBeenCalledWith('/data/withdrawals.json', { cache: 'no-store' });
  fetch.mockImplementation(async () => new Response('', { status: 503 }));
  await expect(assertObjectAvailable('c'.repeat(64))).rejects.toThrow('could not be checked');
  expect(() => validateWithdrawals({ ...registry, extra: true })).toThrow();
  expect(() => validateWithdrawals({ ...registry, editions: {} })).toThrow('Unlinked');
});
